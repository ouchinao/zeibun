import 'normalize.dart';

/// 実務で使う言葉 → 条文の言葉。
///
/// 語の一部が一致しただけで広げないのは、「給料」から「給料日」のような関係の無い
/// 語まで広がり、検索結果が読めなくなるため。条文の言葉は、2026-10 時点の
/// 法人税法・所得税法・消費税法・租税特別措置法の本文に出てくることを確かめてある。
const _synonyms = <String, List<String>>{
  'インボイス': ['適格請求書'],
  'インボイス制度': ['適格請求書'],
  'ボーナス': ['賞与'],
  '給料': ['給与'],
  '退職金': ['退職手当'],
  '役員報酬': ['役員給与'],
  '住宅ローン': ['住宅借入金等'],
  '住宅ローン控除': ['住宅借入金等'],
  'マイナンバー': ['個人番号'],
  '仕入税額控除': ['仕入れに係る消費税額'],
  '簡易課税': ['仕入れに係る消費税額の控除の特例'],
};

/// 検索語ごとに、入力した語と言い換えの語をまとめる。各組の先頭は入力した語。
///
/// 横断検索と本文内検索の両方がこれを使う。片方だけ言い換えると、横断検索で
/// 見つかった条を開いたとき、本文内で一致が見つからないことが起きるため。
List<List<String>> expandSearchTerms(String input) => [
      for (final t in splitSearchTerms(input))
        [
          t,
          for (final s in _synonyms[t] ?? const <String>[])
            if (normalizeForSearch(s) case final n when n != t) n,
        ],
    ];
